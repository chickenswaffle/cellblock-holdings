using System;
using System.IO;
using System.Linq;
using Cellblock.Unity;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;
using UnityEngine.SceneManagement;
using UnityEngine.UIElements;

namespace Cellblock.Editor
{
    [InitializeOnLoad]
    public static class ProjectSetup
    {
        const string ScenePath = "Assets/Cellblock/Scenes/Main.unity";
        const string PipelinePath = "Assets/Cellblock/Settings/CellblockPipeline.asset";
        const string MaterialPath = "Assets/Cellblock/Resources/BuildingMaterial.mat";
        static ProjectSetup() { EditorApplication.delayCall += FirstImport; }
        static void FirstImport()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling) return;
            if (!File.Exists(ScenePath) || !File.Exists(PipelinePath) || !File.Exists(MaterialPath) || !File.Exists("Assets/Cellblock/Resources/DetailedBuildingMaterial.mat") || !File.Exists("Assets/Cellblock/Resources/LuminaireMaterial.mat")) Prepare();
        }
        [MenuItem("Cellblock/Prepare project")]
        public static void Prepare()
        {
            Directory.CreateDirectory("Assets/Cellblock/Scenes"); Directory.CreateDirectory("Assets/Cellblock/Settings");
            AssetDatabase.Refresh();
            var gestures = AssetImporter.GetAtPath("Assets/Plugins/macOS/CellblockGestures.bundle") as PluginImporter;
            if (gestures != null && (gestures.GetCompatibleWithAnyPlatform() || !gestures.GetCompatibleWithEditor()))
            {
                gestures.SetCompatibleWithAnyPlatform(false); gestures.SetCompatibleWithEditor(true);
                gestures.SetEditorData("OS", "OSX"); gestures.SetEditorData("CPU", "AnyCPU");
                gestures.SetCompatibleWithPlatform(BuildTarget.StandaloneOSX, true); gestures.SaveAndReimport();
            }
            var groundImporter = AssetImporter.GetAtPath("Assets/Cellblock/Resources/Textures/GroundMeadow.png") as TextureImporter;
            if (groundImporter != null && (groundImporter.maxTextureSize != 1024 || groundImporter.filterMode != FilterMode.Trilinear))
            {
                groundImporter.maxTextureSize = 1024; groundImporter.mipmapEnabled = true; groundImporter.wrapMode = TextureWrapMode.Repeat;
                groundImporter.filterMode = FilterMode.Trilinear; groundImporter.anisoLevel = 2; groundImporter.SaveAndReimport();
            }
            var pipeline = AssetDatabase.LoadAssetAtPath<UniversalRenderPipelineAsset>(PipelinePath);
            var renderer = AssetDatabase.LoadAssetAtPath<UniversalRendererData>("Assets/Cellblock/Settings/CellblockRenderer.asset");
            if (renderer == null)
            {
                renderer = ScriptableObject.CreateInstance<UniversalRendererData>();
                AssetDatabase.CreateAsset(renderer, "Assets/Cellblock/Settings/CellblockRenderer.asset");
            }
            if (pipeline == null)
            {
                pipeline = UniversalRenderPipelineAsset.Create(renderer);
                pipeline.renderScale = 1; pipeline.msaaSampleCount = 2;
                pipeline.shadowDistance = 55; pipeline.supportsCameraOpaqueTexture = false; pipeline.supportsCameraDepthTexture = false;
                AssetDatabase.CreateAsset(pipeline, PipelinePath);
            }
            // Keep the generated renderer's contact shading and sun shadows visible from the management camera.
            pipeline.shadowDistance = 110; pipeline.supportsCameraDepthTexture = true;
            bool mobile=EditorUserBuildSettings.activeBuildTarget==BuildTarget.iOS||EditorUserBuildSettings.activeBuildTarget==BuildTarget.Android;
            pipeline.mainLightShadowmapResolution=mobile?2048:4096;pipeline.shadowCascadeCount=mobile?2:4;
            ScreenSpaceAmbientOcclusion occlusion = renderer.rendererFeatures.OfType<ScreenSpaceAmbientOcclusion>().FirstOrDefault();
            if (occlusion == null)
            {
                occlusion = ScriptableObject.CreateInstance<ScreenSpaceAmbientOcclusion>(); occlusion.name = "Architectural contact shading";
                AssetDatabase.AddObjectToAsset(occlusion, renderer); renderer.rendererFeatures.Add(occlusion);
                EditorUtility.SetDirty(renderer);
            }
            // Apply on every preparation, including settings generated by earlier revisions.
            var aoSettings = new SerializedObject(occlusion); SerializedProperty values = aoSettings.FindProperty("m_Settings");
            if (values != null)
            {
                values.FindPropertyRelative("Downsample").boolValue = mobile;
                values.FindPropertyRelative("Intensity").floatValue = 1.15f;
                values.FindPropertyRelative("Radius").floatValue = 0.28f;
                values.FindPropertyRelative("DirectLightingStrength").floatValue = 0.22f;
                aoSettings.ApplyModifiedPropertiesWithoutUndo();
            }
            occlusion.Create(); EditorUtility.SetDirty(occlusion);
            EditorUtility.SetDirty(pipeline);
            if (GraphicsSettings.defaultRenderPipeline == null) GraphicsSettings.defaultRenderPipeline = pipeline;
            if (QualitySettings.renderPipeline == null) QualitySettings.renderPipeline = pipeline;
            PrepareMaterial(MaterialPath,false,false);
            PrepareMaterial("Assets/Cellblock/Resources/DetailedBuildingMaterial.mat",true,false);
            PrepareMaterial("Assets/Cellblock/Resources/LuminaireMaterial.mat",false,true);
            if (!File.Exists(ScenePath))
            {
                Scene active = SceneManager.GetActiveScene();
                bool replaceUntitledStartupScene = string.IsNullOrEmpty(active.path);
                if (replaceUntitledStartupScene && active.isDirty)
                    throw new InvalidOperationException("Save the current untitled scene before preparing the Cellblock scene.");
                if (replaceUntitledStartupScene && SceneManager.sceneCount != 1)
                    throw new InvalidOperationException("Save the active untitled scene before preparing Cellblock when multiple scenes are open.");
                Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene,
                    replaceUntitledStartupScene ? NewSceneMode.Single : NewSceneMode.Additive);
                var root = new GameObject("Cellblock Holdings"); root.AddComponent<GameController>();
                SceneManager.MoveGameObjectToScene(root, scene);
                if (!EditorSceneManager.SaveScene(scene, ScenePath))
                {
                    if (!replaceUntitledStartupScene) EditorSceneManager.CloseScene(scene, true);
                    throw new IOException("Unity could not save the generated Cellblock main scene.");
                }
                if (!replaceUntitledStartupScene) EditorSceneManager.CloseScene(scene, true);
            }
            if (EditorBuildSettings.scenes.Length == 0)
                EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(ScenePath, true) };
            PlayerSettings.companyName = "Cellblock Holdings"; PlayerSettings.productName = "Cellblock Holdings";
            PlayerSettings.defaultScreenWidth = 1600; PlayerSettings.defaultScreenHeight = 900;
            PlayerSettings.defaultInterfaceOrientation = UIOrientation.LandscapeLeft;
            PlayerSettings.runInBackground = false;
            PlayerSettings.SetApplicationIdentifier(NamedBuildTarget.iOS, "com.cellblockholdings.game");
            PlayerSettings.iOS.targetOSVersionString = "16.0";
            PlayerSettings.colorSpace = ColorSpace.Linear;
            // The prototype uses Unity's built-in touch/mouse API, with no Input System package requirement.
            UnityEngine.Object[] playerAssets = AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/ProjectSettings.asset");
            if (playerAssets.Length > 0)
            {
                var settings = new SerializedObject(playerAssets);
                SerializedProperty handling = settings.FindProperty("activeInputHandler");
                if (handling != null && handling.intValue != 0) { handling.intValue = 0; settings.ApplyModifiedPropertiesWithoutUndo(); }
            }
            AssetDatabase.SaveAssets();
            Debug.Log("Cellblock project prepared. Open Assets/Cellblock/Scenes/Main.unity and press Play.");
        }
        static void PrepareMaterial(string path,bool normal,bool emission)
        {
            Shader shader=Shader.Find("Universal Render Pipeline/Lit");
            if(shader==null)throw new InvalidOperationException("URP Lit did not import. Resolve the package before preparing the scene.");
            Material material=AssetDatabase.LoadAssetAtPath<Material>(path);
            if(material==null){material=new Material(shader);AssetDatabase.CreateAsset(material,path);}else material.shader=shader;
            material.enableInstancing=true;
            // Retain each runtime feature variant through a Resources material in player builds.
            if(normal)
            {
                const string normalPath="Assets/Cellblock/Settings/FlatNormal.asset";
                Texture2D texture=AssetDatabase.LoadAssetAtPath<Texture2D>(normalPath);
                if(texture==null){texture=new Texture2D(2,2,TextureFormat.RGBA32,false,true){name="Retained linear normal"};texture.SetPixels(new[]{new Color(.5f,.5f,1,1),new Color(.5f,.5f,1,1),new Color(.5f,.5f,1,1),new Color(.5f,.5f,1,1)});texture.Apply();AssetDatabase.CreateAsset(texture,normalPath);}
                material.SetTexture("_BumpMap",texture);material.EnableKeyword("_NORMALMAP");
            }
            else{material.SetTexture("_BumpMap",null);material.DisableKeyword("_NORMALMAP");}
            if(emission){material.EnableKeyword("_EMISSION");material.SetColor("_EmissionColor",Color.white);}
            else{material.DisableKeyword("_EMISSION");material.SetColor("_EmissionColor",Color.black);}
            EditorUtility.SetDirty(material);
        }
        [MenuItem("Cellblock/Validate project")]
        public static void Validate()
        {
            Prepare();
            if (Resources.Load<ThemeStyleSheet>("CellblockTheme") == null || Resources.Load<StyleSheet>("Cellblock") == null)
                throw new InvalidOperationException("The runtime UI theme or stylesheet did not import.");
            if (AssetDatabase.LoadAssetAtPath<SceneAsset>(ScenePath) == null)
                throw new InvalidOperationException("The main scene is missing.");
            if (GraphicsSettings.defaultRenderPipeline == null)
                throw new InvalidOperationException("The URP pipeline is missing.");
            Material material = Resources.Load<Material>("BuildingMaterial");
            if (material == null || material.shader == null)
                throw new InvalidOperationException("The retained player material/shader is missing.");
            foreach(string retained in new[]{"DetailedBuildingMaterial","LuminaireMaterial"})
                if(Resources.Load<Material>(retained)==null)throw new InvalidOperationException("Missing retained material: "+retained);
            Debug.Log("CELLBLOCK_PROJECT_VALIDATION_PASSED");
        }
    }
}
